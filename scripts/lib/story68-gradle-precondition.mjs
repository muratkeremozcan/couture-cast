import fs from 'node:fs'

export const GRADLE_WRAPPER_PRECONDITION = 'android_gradle_wrapper_missing_run_prebuild'

/**
 * The Gradle wrapper belongs to the generated Android project, so a checkout that never ran the
 * prebuild has none. Name that, and the JDK the suites expect, instead of failing later on
 * undefined process output.
 */
export function requireGradleWrapper(
  wrapper,
  { exists = fs.existsSync, env = process.env } = {}
) {
  if (exists(wrapper)) return
  throw new Error(
    `${GRADLE_WRAPPER_PRECONDITION}: ${wrapper} is generated by ` +
      '"node scripts/run-story68-native.mjs prebuild --platform android". ' +
      `These Gradle suites expect Temurin 21 (JAVA_HOME is ${env.JAVA_HOME ?? 'unset'}).`
  )
}

/** stdout plus stderr of a finished process, or the named reason it produced no text. */
export function gradleRunLog(result) {
  if (typeof result?.stdout !== 'string' || typeof result?.stderr !== 'string')
    throw new Error(`gradle_run_produced_no_output:${result?.error?.code ?? 'unknown'}`)
  return result.stdout + result.stderr
}

export function verdictOf(gates) {
  if (gates.length === 0) return 'incomplete'
  if (gates.some((entry) => entry.status === 'failed')) return 'fail'
  if (gates.some((entry) => entry.status !== 'passed')) return 'incomplete'
  return 'pass'
}


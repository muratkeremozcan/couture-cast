function imageEnvironment(inspect) {
  return Object.fromEntries(
    (inspect.Config?.Env ?? []).map((line) => {
      const separator = line.indexOf('=')
      return [line.slice(0, separator), line.slice(separator + 1)]
    })
  )
}


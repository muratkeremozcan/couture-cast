export function getStyleProfileStrings(locale?: string) {
  const guest = getGuestPreviewStrings(locale)
  return {
    ...guest.styleIdeas,
    ...copy[resolveGuestPreviewLocale(locale)],
    ...guest.values.garmentType,
    'mini-skirt': guest.garments['mini-skirt'].name,
    next: guest.gate.submit,
    skip: guest.feedback.skip,
    retry: guest.chrome.retry,
    loadFailed: guest.review.loadFailed,
    saveFailed: guest.review.failed,
    saving: guest.review.saving,
  }
}

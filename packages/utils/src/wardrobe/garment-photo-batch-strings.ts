export function garmentPhotoBatchStrings(locale: string | undefined) {
  const copy = strings[resolveGuestPreviewLocale(locale)]
  return {
    ...copy,
    photo: (count: number) => formatPreviewString(copy.photo, { count }),
    add: (count: number) =>
      count === 1 ? copy.addOne : formatPreviewString(copy.addMany, { count }),
  }
}
